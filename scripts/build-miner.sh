#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/../rust/miner"

cargo build --release --target wasm32-unknown-unknown

rm -rf target/wbindgen-out
wasm-bindgen --target no-modules \
  --out-dir target/wbindgen-out \
  target/wasm32-unknown-unknown/release/miner.wasm

OUT=../../public/miner
cp target/wbindgen-out/miner_bg.wasm      "$OUT/miner_bg.wasm"
cp target/wbindgen-out/miner_bg.wasm.d.ts "$OUT/miner_bg.wasm.d.ts"
cp target/wbindgen-out/miner.d.ts         "$OUT/miner.d.ts"
cp target/wbindgen-out/miner.js           "$OUT/miner_bg.js"
printf '\nexport default wasm_bindgen;\n' >> "$OUT/miner_bg.js"

# Compute a short content hash to bust the browser cache on every rebuild.
WASM_HASH=$(node -e "
const {createHash}=require('crypto');
const {readFileSync}=require('fs');
process.stdout.write(createHash('sha256').update(readFileSync('$OUT/miner_bg.wasm')).digest('hex').slice(0,12));
")

cat > "$OUT/miner.js" <<MINER_JS
/**
 * BitLab miner — browser bridge for the wasm-bindgen "no-modules" glue.
 *
 * miner_bg.js is generated by \`wasm-bindgen --target no-modules\` and made
 * importable as an ES module by appending \`export default wasm_bindgen\`.
 *
 * The ?v= query param is a short content hash of miner_bg.wasm injected at
 * build time — it busts the browser cache whenever the WASM binary changes.
 *
 * Contract consumed by public/miner/worker.js:
 *   import initWasm, { mine_batch, self_test } from './miner.js';
 *   await initWasm('./miner_bg.wasm');
 */
import wasm_bindgen from './miner_bg.js';

export default async function initWasm(pathOrOpts) {
  const url = new URL('miner_bg.wasm', import.meta.url);
  url.searchParams.set('v', '${WASM_HASH}');
  const resolved = typeof pathOrOpts === 'string' ? url.href : url;
  return wasm_bindgen(resolved);
}
export const mine_batch = (...args) => wasm_bindgen.mine_batch(...args);
export const self_test = () => wasm_bindgen.self_test();
export const sha256d_hex = (...args) => wasm_bindgen.sha256d_hex(...args);
export const target_from_bits_hex = (...args) => wasm_bindgen.target_from_bits_hex(...args);
MINER_JS

echo "Artefacts régénérés sous public/miner/ — hash WASM : ${WASM_HASH}"
node "$(dirname "$0")/../scripts/check-miner-wasm.mjs" 2>/dev/null \
  || node "$(dirname "$0")/../../scripts/check-miner-wasm.mjs" 2>/dev/null \
  || echo "(check-miner-wasm skipped)"
