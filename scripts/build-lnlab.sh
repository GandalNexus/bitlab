#!/usr/bin/env bash
set -euo pipefail

WASM_BINDGEN_VERSION=0.2.100

cd "$(dirname "$0")/../rust/lnlab"

command -v wasm-bindgen >/dev/null 2>&1 || {
  echo "wasm-bindgen-cli ${WASM_BINDGEN_VERSION} requis : cargo install wasm-bindgen-cli --version ${WASM_BINDGEN_VERSION} --locked" >&2
  exit 1
}

rustup target add wasm32-unknown-unknown

cargo build --release --target wasm32-unknown-unknown

rm -rf target/wbindgen-out
wasm-bindgen --target no-modules \
  --out-dir target/wbindgen-out \
  target/wasm32-unknown-unknown/release/lnlab.wasm

OUT=../../public/lnlab
cp target/wbindgen-out/lnlab_bg.wasm      "$OUT/lnlab_bg.wasm"
cp target/wbindgen-out/lnlab_bg.wasm.d.ts "$OUT/lnlab_bg.wasm.d.ts"
cp target/wbindgen-out/lnlab.d.ts         "$OUT/lnlab.d.ts"
cp target/wbindgen-out/lnlab.js           "$OUT/lnlab_bg.js"
printf '\nexport default wasm_bindgen;\n' >> "$OUT/lnlab_bg.js"

# Embed a short content hash in the loader shim so browsers never serve
# a stale WASM binary after a rebuild (Cache-Control: no-store + hash param).
WASM_HASH=$(node -e "
const {createHash}=require('crypto');
const {readFileSync}=require('fs');
process.stdout.write(createHash('sha256').update(readFileSync('$OUT/lnlab_bg.wasm')).digest('hex').slice(0,12));
")

cat > "$OUT/lnlab.js" <<LNLAB_JS
/**
 * BitLab lnlab — browser bridge for the wasm-bindgen "no-modules" glue.
 *
 * lnlab_bg.js is generated by \`wasm-bindgen --target no-modules\` and made
 * importable as an ES module by appending \`export default wasm_bindgen\`.
 * Importing .wasm directly as a JS module is refused by browsers (the old
 * "worker: undefined" failure).
 *
 * Contract consumed by worker.js:
 *   import initWasm, { LnLab } from './lnlab.js';
 *   await initWasm({ module_or_path: new URL('lnlab_bg.wasm', import.meta.url) });
 *
 * The ?v= query param is a short content hash of lnlab_bg.wasm injected at
 * build time — it busts the browser cache whenever the WASM binary changes.
 */
import wasm_bindgen from './lnlab_bg.js';

export default async function initWasm(opts) {
  const url = new URL('lnlab_bg.wasm', import.meta.url);
  url.searchParams.set('v', '${WASM_HASH}');
  return wasm_bindgen({ ...opts, module_or_path: url });
}
export const LnLab = wasm_bindgen.LnLab;
LNLAB_JS

echo "artefacts mis à jour dans $OUT (hash WASM : ${WASM_HASH})"
